def grid(name):
    if name in M: rows = [r + r[::-1] for r in M[name].split('\n')]
    else: rows = F[name].split('\n')
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), (name, [len(r) for r in rows])
    return [list(r) for r in rows]

# ---------- 几个用几何算出来更准的 ----------
def blank(): return [['.'] * 16 for _ in range(16)]
def disc(g, cx, cy, r, ch, hole=0):
    for y in range(16):
        for x in range(16):
            d = ((x - cx) ** 2 + (y - cy) ** 2) ** .5
            if hole <= d <= r: g[y][x] = ch
def line(g, x0, y0, x1, y1, ch):
    n = max(abs(x1 - x0), abs(y1 - y0)) or 1
    for i in range(n + 1): g[round(y0 + (y1 - y0) * i / n)][round(x0 + (x1 - x0) * i / n)] = ch
def sun():
    g = blank(); disc(g, 7.5, 7.5, 4.4, '2'); disc(g, 7.5, 7.5, 2.9, '1')
    for x0, y0, x1, y1 in [(7, 1, 7, 1), (8, 1, 8, 1), (7, 14, 7, 14), (8, 14, 8, 14), (1, 7, 1, 7), (1, 8, 1, 8), (14, 7, 14, 7), (14, 8, 14, 8), (2, 2, 3, 3), (13, 2, 12, 3), (2, 13, 3, 12), (13, 13, 12, 12)]: line(g, x0, y0, x1, y1, '1')
    return g
