    g = blank()
    for a in [(7, 1, 7, 14), (8, 1, 8, 14), (1, 7, 14, 7), (1, 8, 14, 8)]: line(g, *a, '2')
    for a in [(3, 3, 12, 12), (12, 3, 3, 12)]: line(g, *a, '1')
    for x, y in [(5, 2), (10, 2), (5, 13), (10, 13), (2, 5), (2, 10), (13, 5), (13, 10)]: g[y][x] = '1'
